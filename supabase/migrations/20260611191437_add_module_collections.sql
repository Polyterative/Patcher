create or replace function public.get_public_module_collection_by_public_id(
  p_public_id text
)
returns table (
  id bigint,
  authorid uuid,
  name text,
  description text,
  image text,
  public boolean,
  public_id text,
  created timestamp without time zone,
  updated timestamp without time zone,
  author jsonb,
  entries jsonb,
  module_count integer
)
language sql
stable
security definer
set search_path = public
as $$
  select
    c.id,
    c.authorid,
    c.name,
    c.description,
    c.image,
    c.public,
    c.public_id,
    c.created,
    c.updated,
    jsonb_build_object('id', p.id, 'username', p.username) as author,
    coalesce((
      select jsonb_agg(
        jsonb_build_object(
          'id', e.id,
          'ordinal', e.ordinal,
          'note', e.note,
          'module', jsonb_build_object(
            'id', m.id,
            'name', m.name,
            'description', m.description,
            'hp', m.hp,
            'public', m.public,
            'manufacturer', jsonb_build_object('id', mf.id, 'name', mf.name),
            'standard', jsonb_build_object('id', s.id, 'name', s.name),
            'created', m.created,
            'updated', m.updated
          )
        )
        order by e.ordinal
      )
      from public.module_collection_entries e
      join public.modules m on m.id = e.module_id and m.public = true
      left join public.manufacturers mf on mf.id = m."manufacturerId"
      left join public.standards s on s.id = m.standard
      where e.collection_id = c.id
    ), '[]'::jsonb) as entries,
    coalesce((
      select count(*)
      from public.module_collection_entries e
      join public.modules m on m.id = e.module_id and m.public = true
      where e.collection_id = c.id
    ), 0)::int as module_count
  from public.module_collections c
  left join public.profiles p on p.id = c.authorid
  where c.public_id = p_public_id
    and c.public = true
  limit 1;
$$;


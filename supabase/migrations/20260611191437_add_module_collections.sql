create or replace function public.get_module_collections_for_module(
  p_module_id bigint
)
returns table (
  id bigint,
  authorid uuid,
  name text,
  description text,
  image text,
  public boolean,
  public_id text,
  created timestamp without time zone,
  updated timestamp without time zone,
  author jsonb,
  module_count integer
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
begin
  return query
  select
    c.id,
    c.authorid,
    c.name,
    c.description,
    c.image,
    c.public,
    c.public_id,
    c.created,
    c.updated,
    jsonb_build_object('id', p.id, 'username', p.username) as author,
    coalesce((
      select count(*)
      from public.module_collection_entries e2
      join public.modules m2 on m2.id = e2.module_id and m2.public = true
      where e2.collection_id = c.id
    ), 0)::int as module_count
  from public.module_collections c
  left join public.profiles p on p.id = c.authorid
  where (
    c.public = true
    or c.authorid = v_user_id
  )
    and exists (
      select 1
      from public.module_collection_entries e
      join public.modules m on m.id = e.module_id and m.public = true
      where e.collection_id = c.id
        and e.module_id = p_module_id
    )
  order by c.updated desc, c.id desc;
end;
$$;

